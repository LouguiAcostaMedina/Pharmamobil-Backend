package pe.edu.upeu.PharmaBackend.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.CommandLineRunner;
import org.springframework.context.annotation.Profile;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Component;
import pe.edu.upeu.PharmaBackend.entity.Categoria;
import pe.edu.upeu.PharmaBackend.entity.Empleado;
import pe.edu.upeu.PharmaBackend.entity.Producto;
import pe.edu.upeu.PharmaBackend.entity.Rol;
import pe.edu.upeu.PharmaBackend.entity.Usuario;
import pe.edu.upeu.PharmaBackend.repository.CategoriaRepository;
import pe.edu.upeu.PharmaBackend.repository.EmpleadoRepository;
import pe.edu.upeu.PharmaBackend.repository.ProductoRepository;
import pe.edu.upeu.PharmaBackend.repository.RolRepository;
import pe.edu.upeu.PharmaBackend.repository.UsuarioRepository;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

@Component
@Profile("h2")
public class H2DataSeeder implements CommandLineRunner {

    private static final Logger log = LoggerFactory.getLogger(H2DataSeeder.class);

    private final JdbcTemplate jdbcTemplate;
    private final CategoriaRepository categoriaRepository;
    private final ProductoRepository productoRepository;
    private final RolRepository rolRepository;
    private final EmpleadoRepository empleadoRepository;
    private final UsuarioRepository usuarioRepository;
    private final PasswordEncoder passwordEncoder;

    public H2DataSeeder(
            JdbcTemplate jdbcTemplate,
            CategoriaRepository categoriaRepository,
            ProductoRepository productoRepository,
            RolRepository rolRepository,
            EmpleadoRepository empleadoRepository,
            UsuarioRepository usuarioRepository,
            PasswordEncoder passwordEncoder) {
        this.jdbcTemplate = jdbcTemplate;
        this.categoriaRepository = categoriaRepository;
        this.productoRepository = productoRepository;
        this.rolRepository = rolRepository;
        this.empleadoRepository = empleadoRepository;
        this.usuarioRepository = usuarioRepository;
        this.passwordEncoder = passwordEncoder;
    }

    @Override
    public void run(String... args) {
        inicializarEsquemaH2SiNoExiste();
        inicializarCatalogo();
        inicializarSeguridad();
    }

    private void inicializarEsquemaH2SiNoExiste() {
        log.info("Verificando / inicializando esquema H2 para seguridad...");
        jdbcTemplate.execute("""
            CREATE TABLE IF NOT EXISTS empleados (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                dni VARCHAR(8) NOT NULL,
                nombres VARCHAR(100) NOT NULL,
                apellidos VARCHAR(100) NOT NULL,
                cargo VARCHAR(60) NOT NULL,
                email VARCHAR(150) NOT NULL,
                telefono VARCHAR(15),
                estado BOOLEAN NOT NULL,
                fecha_creacion TIMESTAMP NOT NULL,
                fecha_modificacion TIMESTAMP,
                CONSTRAINT ux_empleados_dni UNIQUE (dni)
            )
        """);

        jdbcTemplate.execute("""
            CREATE TABLE IF NOT EXISTS roles (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre VARCHAR(30) NOT NULL,
                descripcion VARCHAR(150),
                CONSTRAINT ux_roles_nombre UNIQUE (nombre)
            )
        """);

        jdbcTemplate.execute("""
            CREATE TABLE IF NOT EXISTS usuarios (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(50) NOT NULL,
                password VARCHAR(100) NOT NULL,
                estado BOOLEAN NOT NULL,
                empleado_id BIGINT NOT NULL,
                fecha_creacion TIMESTAMP NOT NULL,
                fecha_modificacion TIMESTAMP,
                CONSTRAINT ux_usuarios_username UNIQUE (username),
                CONSTRAINT ux_usuarios_empleado UNIQUE (empleado_id),
                CONSTRAINT fk_usuarios_empleado FOREIGN KEY (empleado_id) REFERENCES empleados (id)
            )
        """);

        jdbcTemplate.execute("""
            CREATE TABLE IF NOT EXISTS usuario_roles (
                usuario_id BIGINT NOT NULL,
                rol_id BIGINT NOT NULL,
                PRIMARY KEY (usuario_id, rol_id),
                CONSTRAINT fk_usuario_roles_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
                CONSTRAINT fk_usuario_roles_rol FOREIGN KEY (rol_id) REFERENCES roles (id)
            )
        """);
    }

    private void inicializarCatalogo() {
        if (productoRepository.count() == 0) {
            Categoria cat1 = new Categoria(null, "Analgésicos", "Medicamentos para el dolor", true, null, null);
            Categoria cat2 = new Categoria(null, "Antibióticos", "Medicamentos para infecciones", true, null, null);
            categoriaRepository.saveAll(List.of(cat1, cat2));

            Producto p1 = new Producto(null, "Paracetamol 500mg", new BigDecimal("2.50"), 100, true, cat1, null, null);
            Producto p2 = new Producto(null, "Ibuprofeno 400mg", new BigDecimal("3.00"), 50, true, cat1, null, null);
            Producto p3 = new Producto(null, "Amoxicilina 500mg", new BigDecimal("5.00"), 30, true, cat2, null, null);

            productoRepository.saveAll(List.of(p1, p2, p3));
            log.info("====== H2 DATABASE SEEDED WITH CATEGORIES AND PRODUCTS ======");
        }
    }

    private void inicializarSeguridad() {
        // Roles
        Rol rolAdmin = rolRepository.findByNombre("ADMIN").orElseGet(() ->
                rolRepository.save(new Rol(null, "ADMIN", "Administrador con todos los permisos")));
        Rol rolVendedor = rolRepository.findByNombre("VENDEDOR").orElseGet(() ->
                rolRepository.save(new Rol(null, "VENDEDOR", "Registra ventas y atiende clientes")));
        Rol rolAlmacenero = rolRepository.findByNombre("ALMACENERO").orElseGet(() ->
                rolRepository.save(new Rol(null, "ALMACENERO", "Gestiona productos y stock")));

        // Empleados
        Empleado empAdmin = empleadoRepository.findByDni("70123456").orElseGet(() -> {
            Empleado e = new Empleado();
            e.setDni("70123456");
            e.setNombres("Carlos");
            e.setApellidos("Ramirez Torres");
            e.setCargo("Administrador");
            e.setEmail("carlos.ramirez@pharma.pe");
            e.setTelefono("987654321");
            e.setEstado(true);
            e.setFechaCreacion(LocalDateTime.now());
            return empleadoRepository.save(e);
        });

        Empleado empVendedor = empleadoRepository.findByDni("71234567").orElseGet(() -> {
            Empleado e = new Empleado();
            e.setDni("71234567");
            e.setNombres("Lucia");
            e.setApellidos("Fernandez Quispe");
            e.setCargo("Vendedora");
            e.setEmail("lucia.fernandez@pharma.pe");
            e.setTelefono("987111222");
            e.setEstado(true);
            e.setFechaCreacion(LocalDateTime.now());
            return empleadoRepository.save(e);
        });

        Empleado empAlmacen = empleadoRepository.findByDni("72345678").orElseGet(() -> {
            Empleado e = new Empleado();
            e.setDni("72345678");
            e.setNombres("Jorge");
            e.setApellidos("Mendoza Huaman");
            e.setCargo("Almacenero");
            e.setEmail("jorge.mendoza@pharma.pe");
            e.setTelefono("987333444");
            e.setEstado(true);
            e.setFechaCreacion(LocalDateTime.now());
            return empleadoRepository.save(e);
        });

        // Usuarios
        if (!usuarioRepository.existsByUsernameIgnoreCase("admin")) {
            Usuario u = new Usuario();
            u.setUsername("admin");
            u.setPassword(passwordEncoder.encode("Admin123"));
            u.setEstado(true);
            u.setEmpleado(empAdmin);
            u.setRoles(new HashSet<>(Set.of(rolAdmin)));
            u.setFechaCreacion(LocalDateTime.now());
            usuarioRepository.save(u);
            log.info("Usuario 'admin' creado exitosamente.");
        }

        if (!usuarioRepository.existsByUsernameIgnoreCase("vendedor")) {
            Usuario u = new Usuario();
            u.setUsername("vendedor");
            u.setPassword(passwordEncoder.encode("Vendedor123"));
            u.setEstado(true);
            u.setEmpleado(empVendedor);
            u.setRoles(new HashSet<>(Set.of(rolVendedor)));
            u.setFechaCreacion(LocalDateTime.now());
            usuarioRepository.save(u);
            log.info("Usuario 'vendedor' creado exitosamente.");
        }

        if (!usuarioRepository.existsByUsernameIgnoreCase("almacen")) {
            Usuario u = new Usuario();
            u.setUsername("almacen");
            u.setPassword(passwordEncoder.encode("Almacen123"));
            u.setEstado(true);
            u.setEmpleado(empAlmacen);
            u.setRoles(new HashSet<>(Set.of(rolAlmacenero)));
            u.setFechaCreacion(LocalDateTime.now());
            usuarioRepository.save(u);
            log.info("Usuario 'almacen' creado exitosamente.");
        }

        log.info("====== H2 SEGURIDAD INICIALIZADA EXITOSAMENTE ======");
    }
}
